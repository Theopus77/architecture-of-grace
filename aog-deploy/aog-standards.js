/* AOG-STANDARDS-V1 · 2026-09-25
   The Alignment tab's "Academic standards" section: one card per course,
   built from window.AOG_STANDARDS (aog-standards-data.js, generated by
   _work/standards/build_standards.py). Each card opens the unit-by-unit
   table right here, and links to the printable crosswalk at /standards. */
(function () {
  "use strict";
  function T(en, es) { try { return (typeof DT === "function") ? DT(en, es) : en; } catch (e) { return en; } }
  function esc(s) { return String(s == null ? "" : s).replace(/[&<>"]/g, function (c) { return ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c]; }); }

  var CSS = '#xaAcademic .xa-std-sum{font-size:12px;color:var(--ink-faint,#8A92A6);margin:-4px 0 12px}'
    + '#xaAcademic .xa-card{border-left-color:var(--navy,#1B3A5F)}'
    + '#xaAcademic .xa-fw{font-size:11.5px;color:var(--ink-soft,#5b6675);margin:-6px 0 10px}'
    + '#xaAcademic .xa-n{font-family:Fraunces,"Cormorant Garamond",serif;font-size:22px;font-weight:700;color:var(--gold,#B8893A);line-height:1;margin-right:4px}'
    + '#xaAcademic .xa-std-table{border:1px solid var(--rule);border-radius:14px;padding:14px 16px;background:var(--card,#fff);margin:14px 0 6px;max-width:1000px}'
    + '#xaAcademic .xa-std-table[hidden]{display:none}'
    + '#xaAcademic .xa-std-h{font-family:Fraunces,"Cormorant Garamond",serif;font-size:18px;margin:0 0 2px;color:var(--ink)}'
    + '#xaAcademic .xa-std-table .fwn{font-size:12px;color:var(--ink-soft,#5b6675);margin:0 0 10px}'
    + '#xaAcademic table{width:100%;border-collapse:collapse;font-size:12.5px}'
    + '#xaAcademic th{text-align:left;font-size:10px;letter-spacing:.12em;text-transform:uppercase;color:var(--ink-faint,#8A92A6);padding:0 8px 6px;border-bottom:2px solid var(--gold,#B8893A)}'
    + '#xaAcademic td{vertical-align:top;padding:9px 8px;border-bottom:1px solid var(--rule)}'
    + '#xaAcademic td.u{width:32%}'
    + '#xaAcademic td.u b{display:block;font-size:10px;letter-spacing:.1em;text-transform:uppercase;color:var(--gold-deep,#9a6f24)}'
    + '#xaAcademic td.u a{font-weight:700;color:var(--ink);text-decoration:none}'
    + '#xaAcademic td.u a:hover{text-decoration:underline}'
    + '#xaAcademic td.u .m{font-size:11px;color:var(--ink-soft,#5b6675)}'
    + '#xaAcademic td ul{margin:0;padding:0;list-style:none}'
    + '#xaAcademic td li{margin:0 0 4px}'
    + '#xaAcademic code{font-family:ui-monospace,SFMono-Regular,Menlo,monospace;font-size:11px;background:var(--chip,#EFEAE0);color:var(--navy,#1B3A5F);border-radius:6px;padding:1px 6px;margin-right:5px;white-space:nowrap}'
    + 'html[data-theme="dark"] #xaAcademic code{color:var(--gold,#F2C964)}'
    + '@media (max-width:560px){#xaAcademic td.u{width:40%}}';

  function injectCss() {
    if (document.getElementById("aog-standards-css")) return;
    var s = document.createElement("style"); s.id = "aog-standards-css"; s.textContent = CSS; document.head.appendChild(s);
  }

  function tableHtml(c) {
    var rows = c.units.map(function (u) {
      var title = u.link ? '<a href="' + esc(u.link) + '">' + esc(u.title) + '</a>' : esc(u.title);
      var codes = (u.standards || []).map(function (s) { return '<li><code>' + esc(s.code) + '</code>' + esc(s.text) + '</li>'; }).join("")
        || '<li><i>' + esc(T("not yet mapped", "aún sin mapear")) + '</i></li>';
      return '<tr><td class="u"><b>' + esc(T("Unit ", "Unidad ")) + u.n + '</b>' + title + '<div class="m">' + esc(u.band) + (u.strand ? " · " + esc(u.strand) : "") + '</div></td><td><ul>' + codes + '</ul></td></tr>';
    }).join("");
    return '<div class="xa-std-h">' + esc(c.name) + ' · ' + esc(c.subject) + '</div><p class="fwn">' + esc((c.framework || {}).name || "") + ((c.framework || {}).note ? " — " + esc(c.framework.note) : "") + '</p>'
      + '<table><thead><tr><th>' + esc(T("Unit", "Unidad")) + '</th><th>' + esc(T("Standards this unit addresses", "Estándares que aborda esta unidad")) + '</th></tr></thead><tbody>' + rows + '</tbody></table>';
  }

  function render() {
    var host = document.getElementById("xaAcademic");
    var D = window.AOG_STANDARDS;
    if (!host || !D || !D.courses || host.__aogDone) return;
    injectCss();
    var courses = D.courses, nu = 0, nc = 0;
    courses.forEach(function (c) { nu += c.units.length; nc += c.codes; });
    var h = '<div class="xa-sec">' + esc(T("Academic standards · every course", "Estándares académicos · cada curso")) + '</div>'
      + '<p class="xa-std-sum">' + esc(T(courses.length + " courses · " + nu + " units · " + nc + " standards cited. Mapped by the course author from each unit's chapters; open a card to see the unit-by-unit table, or print the whole crosswalk.",
                                          courses.length + " cursos · " + nu + " unidades · " + nc + " estándares citados. Mapeado por el autor del curso a partir de los capítulos; abre una tarjeta para ver la tabla por unidad o imprime el cruce completo.")) + '</p>'
      + '<div class="xa-grid">';
    courses.forEach(function (c, i) {
      var fw = c.framework || {};
      h += '<div class="xa-card"><div class="xa-k">' + esc(T("Standards", "Estándares")) + ' · ' + esc(fw.short || "") + '</div>'
        + '<div class="xa-t">' + esc(c.name) + '</div>'
        + '<div class="xa-fw">' + esc(c.subject) + '</div>'
        + '<div class="xa-d"><span class="xa-n">' + c.codes + '</span> ' + esc(T("standards across", "estándares en")) + ' ' + c.units.length + ' ' + esc(T("units — ", "unidades — ")) + esc(fw.name || "") + '.</div>'
        + '<div class="xa-acts"><button type="button" class="xa-link xa-std-btn" data-i="' + i + '" aria-expanded="false">' + esc(T("Show the units", "Ver las unidades")) + '</button>'
        + '<a class="xa-link xa-ghost" href="/standards-crosswalk#' + esc(c.key) + '" target="_blank" rel="noopener">' + esc(T("Print", "Imprimir")) + '</a>'
        + (c.hubExists ? '<a class="xa-link xa-ghost" href="' + esc(c.hub) + '">' + esc(T("Course", "Curso")) + '</a>' : '') + '</div></div>';
    });
    h += '</div><div class="xa-std-table" id="xaStdTable" hidden></div>';
    host.innerHTML = h;
    host.__aogDone = true;
    host.addEventListener("click", function (e) {
      var b = e.target.closest ? e.target.closest(".xa-std-btn") : null; if (!b) return;
      var i = +b.getAttribute("data-i"), box = document.getElementById("xaStdTable");
      var open = b.getAttribute("aria-expanded") === "true";
      host.querySelectorAll(".xa-std-btn").forEach(function (x) { x.setAttribute("aria-expanded", "false"); x.textContent = T("Show the units", "Ver las unidades"); });
      if (open) { box.hidden = true; return; }
      box.innerHTML = tableHtml(courses[i]); box.hidden = false;
      b.setAttribute("aria-expanded", "true"); b.textContent = T("Hide the units", "Ocultar las unidades");
      try { box.scrollIntoView({ block: "nearest", behavior: "smooth" }); } catch (e2) {}
    });
  }

  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", render); else render();
  setTimeout(render, 800);
  try { window.aogRenderStandards = render; } catch (e) {}
})();
