def section_for(n, band, nch=None):
    """The practice section for unit n (or None). Checks become {"q","choices","a","why"} in assemble.py."""
    if n not in U: return None
    lessons = [SAFETY[LEVEL_OF_BAND[band]]] + U[n]
    return {"title": SECTION_TITLE, "practice": True, "lessons": [dict(l) for l in lessons]}


def unit_moves(n):
    return [l["move"] for l in U.get(n, [])]


def links_for(n):
    """Practice-room doors for unit n: the Dojo, and the other side of each one-sided move."""
    out = []
    ids = unit_moves(n)
    if not ids: return out
    out.append((DOJO, "The Dojo — every move in 3D"))
    for mid in ids:
        en, es, sided = MOVES[mid]
        if sided: out.append((other_side(mid), "The Dojo — %s, other side" % en))
    return out
